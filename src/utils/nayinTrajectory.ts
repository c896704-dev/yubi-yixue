// ============================================================
// 二、纳音×本命"得地"档（计算，非查表）
//     《三命通会·论大运》：纳音与命相孚同类最爲上吉，财官次之，若泄气或受克重则不吉。
//     本命 = 年命纳音五行（古法以年为本）或日主命五行（子平以日为主）——两口径都给。
// ============================================================

export type DeDiKind = '同类上吉' | '得地' | '财官次之' | '泄气' | '受克不吉'

export interface DeDiResult {
  kind: DeDiKind
  label: string
  desc: string
}

/**
 * 岁运纳音五行(ming=命主五行) × 运纳音五行(yun) 的关系。
 * 命主在上、运在下来作用：
 *   同气 → 同类上吉；运生命 → 得地（生气来朝）；命克运 → 财官（我去制，主进取有功）；
 *   命生运 → 泄气（我生者盗气，主劳而少功）；运克命 → 受克不吉（鬼来临身）。
 */
export function nayinDeDi(mingElem: FiveElement, yunElem: FiveElement): DeDiResult {
  if (mingElem === yunElem) return { kind: '同类上吉', label: '纳音同气·上吉', desc: '《三命通会》谓"纳音与命相孚同类最爲上吉"——行运纳音与本命同气，此运顺遂得力' }
  if (generates(yunElem, mingElem)) return { kind: '得地', label: '纳音得地·生气来朝', desc: '运之纳音生本命，如木人行北方水地——主滋养护持，宜进取' }
  if (controls(mingElem, yunElem)) return { kind: '财官次之', label: '纳音财官·我制为用', desc: '本命克运之纳音，我去制之为财官——主经营可得，但须出力，"财官次之"' }
  if (generates(mingElem, yunElem)) return { kind: '泄气', label: '纳音泄气·劳而少功', desc: '本命生运之纳音，我生者盗我之气——主付出多回报少，宜守不宜贪' }
  return { kind: '受克不吉', label: '纳音受克·鬼来临身', desc: '运之纳音克本命，如金人行南方火地——主受制受压，宜谨慎退避' }
}

