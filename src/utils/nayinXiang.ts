/** 胎息：某柱干合支合化出之柱（《兰台妙选》古法"干合支合为胎息"）。
 *  如日柱辛卯 → 丙戌（丙辛合、卯戌合），纳音屋上土 */
export function getTaiXi(ganzhi: string): string {
  const gan = GAN_HE[ganzhi.charAt(0)]!
  const zhi = ZHI_HE[ganzhi.charAt(1)]!
  return gan + zhi
}
